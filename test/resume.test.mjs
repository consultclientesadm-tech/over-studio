import { createRequire } from 'module'; import { spawn } from 'child_process';
const { chromium } = createRequire(import.meta.url)('playwright');
const srv = spawn('node', ['server.js'], { env: { ...process.env, PORT: '8097' }, stdio: 'ignore', cwd: process.cwd() });
await new Promise((r) => setTimeout(r, 600));
const b = await chromium.launch(); const c = await b.newContext({ viewport: { width: 390, height: 844 }, userAgent: 'Mozilla/5.0 (iPhone; CPU iPhone OS 18_0 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/18.0 Mobile/15E148 Safari/604.1', isMobile: true, hasTouch: true });
const p = await c.newPage(); p.on('pageerror', (e) => console.log('[erro]', e.message));
await p.route(/fonts\./, (r) => r.abort());
await p.goto('http://localhost:8097/');
await p.setInputFiles('#file', process.argv[2]);
await p.waitForTimeout(3000);
console.log('antes do "crash":', await p.evaluate(() => [document.getElementById('app').dataset.screen, localStorage.getItem('sc-run')?.slice(0, 60)]));
await p.reload();
await p.waitForTimeout(1500);
console.log('depois de recarregar:', await p.evaluate(() => [document.getElementById('app').dataset.screen, document.getElementById('toast').textContent.slice(0, 60)]));
await p.waitForFunction(() => document.getElementById('app').dataset.screen === 'studio', null, { timeout: 300000 });
await p.waitForTimeout(1500);
console.log('chegou no estúdio sozinho:', await p.evaluate(() => [document.getElementById('app').dataset.screen, !!document.querySelector('.lastrun')]));
const left = await p.evaluate(() => new Promise((res) => { const r = indexedDB.open('studio-cover', 1); r.onsuccess = () => { const q = r.result.transaction('f').objectStore('f').count(); q.onsuccess = () => res(q.result); }; }));
console.log('arquivos guardados depois de terminar:', left);
await b.close(); srv.kill();
